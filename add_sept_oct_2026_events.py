def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    rows = []
    for e in EVENTS:
        (title, date_str, location, city, address_suffix, tags, summary, description,
         img_key, fee, organizer, parking_info, target_age,
         free_parking, stroller_ok, rainy_ok, category_scene) = e

        lat, lng, official_url = CITY_INFO[city]
        address = f"静岡県{city}{address_suffix}"
        google_maps_url = f"https://maps.google.com/?q={lat},{lng}"
        image_url = IMG[img_key]

        rows.append((
            "event", title, date_str, location, city, address, lat, lng,
            google_maps_url, official_url, tags, summary, description, image_url,
            fee, organizer, parking_info, target_age,
            free_parking, stroller_ok, rainy_ok, category_scene
        ))

    cur.executemany("""
        INSERT INTO events (
            item_type, title, date_str, location, city, address, lat, lng, google_maps_url, official_url,
            tags, summary, description, image_url, fee, organizer, parking_info, target_age,
            is_free_parking, is_stroller_ok, is_rainy_ok, category_scene
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, rows)

    conn.commit()
    conn.close()
    print(f"Inserted {len(rows)} events (2026年9-10月).")

